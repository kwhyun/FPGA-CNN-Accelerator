"""rtl/accel_top.sv port list → Verilog wrapper for Vivado module reference (rtl/accel_wrap.v).

    python -m compiler.codegen.gen_wrapper
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "rtl" / "accel_top.sv"
DST = ROOT / "rtl" / "accel_wrap.v"
PORT = re.compile(r"^\s*(input|output)\s+wire\s*(\[[^\]]+\])?\s*(\w+)\s*,?\s*$")


def ports() -> list[tuple[str, str, str]]:
    text = SRC.read_text()
    body = text[text.index("module accel_top"): text.index(");")]
    out = []
    for line in body.splitlines():
        m = PORT.match(line)
        if m:
            out.append((m.group(1), (m.group(2) or "").replace(" ", ""), m.group(3)))
    return out


def render() -> str:
    ps = ports()
    lines = ["// Auto-generated by compiler/codegen/gen_wrapper.py from rtl/accel_top.sv. DO NOT EDIT.",
             "// Vivado block-design module references require a Verilog top file.",
             "`default_nettype none", "module accel_wrap ("]
    decl = []
    for d, w, n in ps:
        attr = ""
        if n == "clk":
            attr = ('  (* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 clk CLK" *)\n'
                    '  (* X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF s_axil:m_axi_in:m_axi_w:m_axi_out, '
                    'ASSOCIATED_RESET rst_ni" *)\n')
        elif n == "rst_ni":
            attr = ('  (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 rst_ni RST" *)\n'
                    '  (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_LOW" *)\n')
        elif n == "irq_o":
            attr = ('  (* X_INTERFACE_INFO = "xilinx.com:signal:interrupt:1.0 irq_o INTERRUPT" *)\n'
                    '  (* X_INTERFACE_PARAMETER = "SENSITIVITY LEVEL_HIGH" *)\n')
        decl.append(f"{attr}  {d} wire {w + ' ' if w else ''}{n}")
    lines.append(",\n".join(decl))
    lines.append(");")
    lines.append("  accel_top u_accel_top (")
    lines.append(",\n".join(f"    .{n}({n})" for _, _, n in ps))
    lines.append("  );")
    lines.append("endmodule")
    lines.append("`default_nettype wire")
    return "\n".join(lines) + "\n"


def main() -> int:
    DST.write_text(render())
    print(f"wrote {DST} ({len(ports())} ports)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
