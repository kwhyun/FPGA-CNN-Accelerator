"""Board outputs: model.bin (DDR image), images.bin (N first-layer inputs), board_model.h.

    python -m compiler.codegen.export_board --model resnet50 --n 1000   # build/resnet50/board/
The FSBL loads model.bin at MODEL_DDR_BASE and images.bin at IMAGES_DDR_BASE (boot.bif).
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

from compiler.codegen.layout import c8, pack_fmap
from compiler.codegen.program import DDR_BASE, build_program
from compiler.model.config import model_build_dir, model_config
from compiler.model.images import label
from compiler.model.inputs import first_layer_input, load_image
from compiler.model.ir import load_model

IMAGES_DDR_BASE = 0x1400_0000
DDR_END = 0x2000_0000          # ZedBoard 512 MiB


def export(name: str, n: int, start: int, out: Path) -> dict:
    model = load_model(name)
    cfg = model_config(name)
    prog = build_program(model, None)
    size = prog.end_addr - DDR_BASE
    blob = bytearray(size)
    for addr, data in prog.regions.items():
        blob[addr - DDR_BASE: addr - DDR_BASE + len(data)] = data
    first = model.layers[0]
    in_bytes = len(pack_fmap(np.zeros(model.input_shape, np.int8), model.input_zp, first.in_dense))
    stride = -(-in_bytes // 64) * 64
    if DDR_BASE + size > IMAGES_DDR_BASE or IMAGES_DDR_BASE + n * stride > DDR_END:
        raise ValueError("DDR map overflow")
    out.mkdir(parents=True, exist_ok=True)
    (out / "model.bin").write_bytes(bytes(blob))
    labels = []
    with open(out / "images.bin", "wb") as f:
        for i in range(start, start + n):
            x = first_layer_input(model, load_image(cfg, i))
            f.write(pack_fmap(x, model.input_zp, first.in_dense).ljust(stride, b"\0"))
            labels.append(label(i))
    last = model.layers[-1]
    logits_addr = prog.tensor_addr[last.output]
    instr0_in_base = prog.instr_addr + 44     # word5[63:32]
    h = [
        "// Auto-generated by compiler/codegen/export_board.py. DO NOT EDIT.",
        "#ifndef BOARD_MODEL_H", "#define BOARD_MODEL_H", "#include <stdint.h>",
        f'#define MODEL_NAME "{name}"',
        f"#define MODEL_DDR_BASE 0x{DDR_BASE:08X}u", f"#define MODEL_BYTES {size}u",
        f"#define INSTR_ADDR 0x{prog.instr_addr:08X}u", f"#define INSTR_COUNT {len(prog.instrs)}u",
        f"#define INSTR0_IN_BASE_ADDR 0x{instr0_in_base:08X}u",
        f"#define IMAGES_DDR_BASE 0x{IMAGES_DDR_BASE:08X}u", f"#define IMAGE_STRIDE {stride}u",
        f"#define N_IMAGES {n}u", f"#define FIRST_IMAGE_INDEX {start}u",
        f"#define LOGITS_ADDR 0x{logits_addr:08X}u", f"#define NUM_CLASSES {model.num_classes}u",
        f"#define CLASS_OFFSET {model.class_offset}u",
        "static const uint16_t image_label[N_IMAGES] = {",
        ",\n".join("  " + ",".join(map(str, labels[i:i + 20])) for i in range(0, n, 20)),
        "};", "#endif", "",
    ]
    (out / "board_model.h").write_text("\n".join(h))
    manifest = {
        "model": name, "n": n, "start": start, "model_bytes": size,
        "model_sha256": hashlib.sha256(blob).hexdigest(),
        "images_sha256": hashlib.sha256((out / "images.bin").read_bytes()).hexdigest(),
        "model_ddr_base": DDR_BASE, "images_ddr_base": IMAGES_DDR_BASE, "logits_addr": logits_addr,
        "logits_bytes": c8(last.c_out),
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1))
    return manifest


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--n", type=int, default=1000)
    ap.add_argument("--start", type=int, default=1)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()
    out = args.out or model_build_dir(args.model) / "board"
    m = export(args.model, args.n, args.start, out)
    print(f"{args.model}: model.bin {m['model_bytes']} B, images {args.n} -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
